export function getCompany(slug: string): Company | undefined {
  return COMPANIES.find((c) => c.slug === slug);
}

export function getCompanyByTicker(ticker: string): Company | undefined {
  return COMPANIES.find((c) => c.ticker?.toUpperCase() === ticker.toUpperCase());
}

export function publicCompanies(): Company[] {
  return COMPANIES.filter((c) => c.isPublic);
}

export function privateCompanies(): Company[] {
  return COMPANIES.filter((c) => !c.isPublic);
}

export function purePlays(): Company[] {
  return COMPANIES.filter((c) => c.purity === 'pure_play');
}
