export function getRecentNews(limit = 20): NewsArticle[] {
  return [...SEED_NEWS]
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())
    .slice(0, limit);
}

export function getNewsForCompany(slug: string, limit = 10): NewsArticle[] {
  return SEED_NEWS
    .filter((n) => n.companyTags.includes(slug))
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())
    .slice(0, limit);
}
